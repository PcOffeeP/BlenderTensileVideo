def timeline(frame):
 t=(frame-1)/FPS; lp=smooth(t/LOAD_END); travel=MAX_JAW_TRAVEL*lp
 if a.control_no_slip:
  return t,travel,travel,0.,0.
 sp=smooth((t-SLIP_START)/(SLIP_END-SLIP_START))
 recoil=smooth((t-PLANNED_EXIT_S)/(SETTLE_END-PLANNED_EXIT_S))
 elongation=travel-MAX_SLIP*sp
 # Remaining elastic-like extension returns as bending starts immediately
 # after the planned clearance frame; actual clearance is independently checked.
 elongation=(1.-recoil)*elongation
 return t,travel,elongation,MAX_BEND*recoil,MAX_SLIP*sp

def nominal_width(u):
 shoulder=max(smooth((.25-u)/.15),smooth((u-.75)/.15))
 return .14+(.44-.14)*shoulder

def stretch_weight(u):
 return smooth((u-.10)/.15)*smooth((.90-u)/.15)

SEGMENT_REST=REST/N
SEGMENT_WEIGHTS=[stretch_weight((i+.5)/N) for i in range(N)]
WEIGHT_INTEGRAL=sum(SEGMENT_REST*w for w in SEGMENT_WEIGHTS)

def specimen_geometry(frame):
 t,jaw,extension,theta,slip=timeline(frame)
 free0=REST*(1.-HELD); free_length=free0+extension
 # Material arc length is integrated from a local stretch field; both grip
 # sections remain unstrained while the free part receives the extension.
 arc=[0.]
 for weight in SEGMENT_WEIGHTS:
  arc.append(arc[-1]+SEGMENT_REST*(1.+extension*weight/WEIGHT_INTEGRAL))
 verts=[]
 for i in range(N+1):
  u=i/N
  if u<=HELD:
   cx=0.; cz=BOTTOM+REST*u; angle=0.
  else:
   s=(arc[i]-REST*HELD)/free_length; angle=theta*s
   if abs(theta)<1e-9:
    cx=0.; cz=BOTTOM+REST*HELD+free_length*s
   else:
    radius=free_length/theta
    cx=radius*(1.-math.cos(angle)); cz=BOTTOM+REST*HELD+radius*math.sin(angle)
  # Width and thickness use the local axial stretch rather than a global
  # scale; the held ends remain fixed. This approximates volume conservation,
  # but does not model the polymer's constitutive response.
  lam=1.+extension*stretch_weight(u)/WEIGHT_INTEGRAL
  factor=1./math.sqrt(lam)
  width=nominal_width(u)*factor; thick=THICKNESS*factor
  nx=math.cos(angle); nz=-math.sin(angle)
  for sx,sy in [(-1,-1),(1,-1),(1,1),(-1,1)]:
   verts.append((cx+sx*width*.5*nx,sy*thick*.5,cz+sx*width*.5*nz))
 faces=[]
 for i in range(N):
  lo=4*i;hi=4*(i+1)
  for j in range(4):faces.append((lo+j,lo+(j+1)%4,hi+(j+1)%4,hi+j))
 faces.extend([(3,2,1,0),tuple(4*N+j for j in range(4))])
 return verts,faces

