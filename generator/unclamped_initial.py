def clip_z(poly,limit,keep_above):
 if not poly:return []
 result=[]
 for left,right in zip(poly,poly[1:]+poly[:1]):
  inside_l=(left.z>=limit) if keep_above else (left.z<=limit)
  inside_r=(right.z>=limit) if keep_above else (right.z<=limit)
  if inside_l:result.append(left)
  if inside_l!=inside_r:
   ratio=(limit-left.z)/(right.z-left.z);result.append(left.lerp(right,ratio))
 return result

